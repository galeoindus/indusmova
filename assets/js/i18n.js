let active = 'en';

export function setUiLang(code) {
  active = STRINGS[code] ? code : 'en';
  if (typeof document !== 'undefined') document.documentElement.setAttribute('lang', active === 'hi' ? 'hi' : 'en');
  return active;
}

export function getUiLang() {
  return active;
}

/** Translate a key, interpolating {name} placeholders from `vars`. */
export function t(key, vars) {
  const dict = STRINGS[active] || STRINGS.en;
  let text = dict[key] ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, v);
  return text;
}

/** Apply translations to a subtree: [data-i18n], [data-i18n-ph], [data-i18n-title]. */
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((node) => {
    node.textContent = t(node.getAttribute('data-i18n'));
  });
  root.querySelectorAll('[data-i18n-ph]').forEach((node) => {
    node.setAttribute('placeholder', t(node.getAttribute('data-i18n-ph')));
  });
  root.querySelectorAll('[data-i18n-title]').forEach((node) => {
    node.setAttribute('title', t(node.getAttribute('data-i18n-title')));
  });
  root.querySelectorAll('[data-i18n-aria]').forEach((node) => {
    node.setAttribute('aria-label', t(node.getAttribute('data-i18n-aria')));
  });
}
